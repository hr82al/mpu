/**
 * Приёмник вывода удалённой команды. Объявлен на стороне пакета ровно
 * в той мере, в какой пакет его зовёт: потребитель передаёт свой объект
 * как есть.
 */

/** Куда течёт вывод удалённой команды. */
export interface RemoteSink {
  /**
   * Кусок вывода. Ответ — обещание готовности принять следующий: пока оно
   * не разрешено, следующий кусок не читается, и медленный читатель
   * притормаживает удалённую команду, а не копится в памяти
   * (`platform/line-cancel.md`, «Вывод — по мере появления»).
   */
  readonly out: (chunk: Uint8Array) => Promise<void>;
  /** То же для stderr. */
  readonly err: (chunk: Uint8Array) => Promise<void>;
}
