/**
 * Файл, прикладываемый к сообщению. Тип общий на два канала — личный
 * аккаунт (MTProto) и личного бота (Bot API): протоколы разные, а
 * вложение одно. Чтение с диска — дело потребителя: тексты его отказов
 * принадлежат вводу команды, не слою Telegram.
 */

/** Файл, уходящий документом без превью; несколько — альбом. */
export interface Attachment {
  /** Имя файла в Telegram: файлы уходят под своими именами. */
  readonly name: string;
  readonly bytes: Uint8Array;
}
