const COMMANDS = [
  codeLiteralsCommand,
  codeShapeCommand,
  codeRefsCommand,
  codeTwinsCommand,
  codeNameCommand,
  codeMentionsCommand,
];

describe("справка называет весь состав, заданный спекой", () => {
  for (const command of COMMANDS) {
    const name = command.path.join(" ");
    it(name, () => {
      const required = REQUIRED[name];
      // Проверка задумана как гейт для будущих поверхностей семейства:
      // без этой строки команда вне таблицы падала бы `TypeError`, а не
      // сообщением о том, что состав её справки не описан.
      expect(required !== undefined, `${name}: состав справки не описан`).toBe(
        true,
      );
      for (const phrase of required) {
        expect(
          command.help.includes(phrase),
          `${name}: справка не называет «${phrase}»`,
        ).toBe(true);
      }
    });
  }
});

describe("пример вызова из справки — полный и разбирается", () => {
  for (const command of COMMANDS) {
    const name = command.path.join(" ");
    it(name, () => {
      const examples = command.examples;
      expect(examples.length > 0, `${name}: примеров нет вовсе`).toBe(true);
      for (const example of examples) {
        // Существования адреса и окна на диске не требуется: пример,
        // ссылающийся на живой исходник, устаревает от первой же правки
        // (`specs/code-twins.md`, «CLI-контракт»). Требуется, чтобы он
        // был полным вызовом и чтобы его адрес либо окно разбирались.
        const tail = example.slice(`mpu ${name} `.length).split(" ");
        if (name === "code name" || name === "code mentions") {
          // Пример без окна проверять нечем: in: обязан быть в нём и
          // обязан нести значение, иначе разбор молча уходит в имя.
          const at = tail.indexOf("in:");
          expect(at >= 0, `${name}: в примере нет in:`).toBe(true);
          expect(at + 1 < tail.length, `${name}: у in: нет значения`).toBe(
            true,
          );
          parseWindow(tail[at + 1]);
          continue;
        }
        if (name === "code twins" && tail[0] === "base:") {
          // Режим по диффу: адреса нет, у base: и in: есть значения
          // (`specs/code-twins.md`, «Режим по диффу»).
          const at = tail.indexOf("in:");
          expect(tail.length, `${name}: пример по диффу`).toBe(4);
          expect(at, `${name}: в примере по диффу нет in:`).toBe(2);
          continue;
        }
        expect(tail[0], `${name}: адрес не ключом`).toBe("address:");
        parseAddress(tail[1]);
      }
    });
  }
});
