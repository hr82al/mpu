/**
 * Версия сборки бинаря. Константа, а не чтение файла в рантайме: после
 * `deno compile` рядом с бинарём ничего нет, а `server/discover` обязан
 * назвать версию, чтобы клиент видел отставший процесс сервера
 * (`platform/mcp-server.md`).
 *
 * Значение привязано к машинному слепку дерева команд: реестр порождён
 * из слепка, поэтому версия бинаря — это версия того дерева, на которое
 * он рассчитан. Совпадение стережёт тест `version_test.ts`, а
 * расхождение с фактически установленной Python-реализацией ловится
 * при старте MCP-сервера (`mcp/cli.ts`).
 */
export const VERSION = "0.1.0";

/**
 * Как понимать расхождение версий. Бинарь и Python-реализация —
 * разные артефакты одной системы: первый несёт реестр и схемы команд,
 * снятые со слепка, второй исполняет команды маршрута `legacy`. Разошлись
 * — описания тулов и однострокѝ справки могут врать, поэтому молчать
 * об этом нельзя.
 */
export function versionMismatch(
  legacyVersion: string,
): string | undefined {
  const installed = legacyVersion.trim();
  if (installed === "" || installed === VERSION) return undefined;
  return `версия legacy-реализации (${installed}) расходится ` +
    `с версией сборки (${VERSION}): состав команд и описания тулов ` +
    `сняты со слепка ${VERSION} и могут не совпадать с установленной`;
}
