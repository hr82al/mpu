/**
 * Каталог вызова (`platform/line-concurrency.md`): относительные пути
 * разрешаются от него, а не от каталога процесса. У сервера строк
 * каталог перестаёт быть состоянием процесса — у каждой строки он свой,
 * и спрашивают о нём объект, а не `Deno.cwd()`. Модуль общий: его берут
 * и сервер строк, и те команды, что ходят к файлам и подпроцессам мимо
 * портов `CommandIo` (`src/d2miro`).
 */

/** Каталог, в котором исполняется вызов. */
export class Workdir {
  readonly #path: string;

  /** @param path абсолютный каталог вызова (поле `cwd` первого кадра) */
  constructor(path: string) {
    this.#path = path;
  }

  /** Сам каталог вызова. */
  path(): string {
    return this.#path;
  }

  /**
   * Путь, по которому искать файл: абсолютный — как есть,
   * относительный — от каталога вызова. Пустой путь — сам каталог.
   * Нормализацией не занимаемся:
   * `a/./b` понимает сама файловая система.
   */
  resolve(path: string): string {
    if (path.startsWith("/")) return path;
    if (path === "") return this.#path;
    return `${this.#path}/${path}`;
  }
}
