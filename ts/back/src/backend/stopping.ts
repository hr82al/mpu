/**
 * Просьба строке остановиться (`platform/line-cancel.md`): её посылает
 * тот, кто перестал слушать, а решает по ней сама строка. Здесь же
 * единственное место, где причина конца строки превращается в код: у
 * остановленной он свой, и называется он один раз.
 */

/** Код остановленной строки: 128 + SIGINT, как у прерванного процесса. */
export const CANCELLED_CODE = 130;

/** Чем строку просят остановиться и чем она об этом узнаёт. */
export class Stopping {
  readonly #controller = new AbortController();

  /** Сигнал для исполнения: его видит команда портом `CommandIo`. */
  signal(): AbortSignal {
    return this.#controller.signal;
  }

  /** Попросить остановиться; повторная просьба ничего не меняет. */
  ask() {
    this.#controller.abort();
  }

  /**
   * Код строки: остановленной — свой, прочей — код её команды.
   *
   * Спрашивается после исполнения, а не по факту обрыва канала: обрыв
   * мог прийти уже после того, как команда кончилась сама, и тогда итог
   * у строки прежний (`platform/line-cancel.md`, «Инварианты»).
   *
   * @param code код, которым кончилась команда
   */
  outcome(code: number): number {
    return this.#controller.signal.aborted ? CANCELLED_CODE : code;
  }
}
