/**
 * Протоколы вычислителя (`docs/specs/platform/evaluator.md`): значение
 * программы, его ответ и запрос машине. Здесь только интерфейсы:
 * реализации — в соседних файлах.
 */

/**
 * Машина глазами запроса: куда положить кадр блока, чем ответить на
 * запрос, что напечатать и как спросить ядро.
 */
export interface Stack {
  /**
   * Кадр вызванного блока: его итог вернётся тому, кто позвал.
   *
   * @param label место кадра в тексте ошибки (`блок each:`)
   */
  push(activation: Answer, label: string): void;
  /** Ответ на запрос без нового кадра. */
  resume(value: Value): void;
  /** Печать программы (`print`): текст уходит в stdout строки. */
  print(text: string): void;
  /** Команда реестра — ядру отдельной строкой. */
  core(words: readonly string[]): Promise<Reply>;
}

/**
 * Итог строки ядра глазами программы: результат значением либо текст,
 * который строка напечатала (формат за командой). Строка, кончившаяся
 * кодом ≠ 0, отвечает на оба концом программы.
 */
export interface Reply {
  value(): Value;
  printed(): Value;
}

/** Запрос ответа машине: вызов блока, печать, строка ядру. */
export interface Request {
  enter(stack: Stack): Promise<void>;
}

/**
 * Ответ на сообщение: генератор, который может попросить машину вызвать
 * блок или спросить ядро, а итог отдаёт значением. Глубина вызовов блоков
 * живёт в куче машины, а не на стеке JS.
 */
export type Answer = Generator<Request, Value, Value>;

/**
 * Значение как операнд чужой операции: число, текст или ни то ни другое.
 * Операцию решает получатель, а операнд отвечает за свою сторону
 * (двойная диспетчеризация без проверки типа).
 */
export interface Operand {
  /** Число для арифметики `selector`; не число — отказ. */
  amount(selector: string): number;
  /** Порядок числа `n` относительно операнда: < 0, 0 или > 0. */
  fromNumber(n: number): number;
  /** Порядок текста `t` относительно операнда по кодовым точкам. */
  fromText(t: string): number;
  /** Равно ли операнду число `n`. */
  isNumber(n: number): boolean;
  /** Равен ли операнду текст `t`. */
  isText(t: string): boolean;
  /** Содержится ли текст операнда в `t` без учёта регистра. */
  within(t: string): boolean;
}

/** Значение программы: объект, отвечающий на сообщения. */
export interface Value {
  /**
   * Сколько первых ключей склеенного ключевого сообщения значение
   * понимает одним своим сообщением; ни одного — 0. Остаток уходит
   * результату (деление склеенного, `platform/line-grammar.md` [D.2]).
   */
  take(keys: readonly string[]): number;
  /**
   * Ответ на сообщение `selector` (ключевое — ключи по порядку строки с
   * двоеточиями, `to:do:`); непонятое — отказ `doesNotUnderstand`.
   */
  send(selector: string, args: readonly Value[]): Answer;
  /** Вид печати с переводом строки в конце; `nil` — пусто. */
  shown(): string;
  /** Элемент в построчном виде списка — без перевода строки. */
  line(): string;
  /**
   * Текст значения ключа команды (`platform/value-expression.md`):
   * скаляр — его текст; прочее — отказ «не скаляр».
   */
  spelled(key: string): string;
  /** Значение как операнд чужой арифметики и сравнения. */
  operand(): Operand;
  /**
   * Вызов значения блоком со значениями `args`; `by` — сообщение, ради
   * которого вызов (место кадра в тексте ошибки). Не блок — отказ
   * `doesNotUnderstand value…`.
   */
  evaluated(args: readonly Value[], by: string): Answer;
  /**
   * Значение как условие итога блока `by` (`select:`, `detect:`):
   * булево — своё; прочее — отказ.
   */
  condition(by: string): boolean;
  /** Данные значения для формата `json`. */
  json(): unknown;
}
