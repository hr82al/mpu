/**
 * Команда → строка для удалённого шелла (`platform/exec-transport.md`,
 * «Команда → shell-строка»). Правило живёт здесь, а не в бэкендах:
 * инвариант спеки требует одинаковой строки для одной и той же команды
 * независимо от того, каким транспортом она поедет.
 */

/**
 * Символы, безопасные в POSIX-шелле без кавычек. Список — минимально
 * достаточный: всё, чего в нём нет, квотируется, поэтому ошибка в
 * сторону лишних кавычек безобидна, а в другую — нет.
 */
const SAFE = /^[A-Za-z0-9_@%+=:,./-]+$/;

/**
 * Элемент команды атомарно: спецсимволы внутри аргумента шеллу не видны.
 * Одинарные кавычки внутри закрываются и вносятся двойными — способ,
 * работающий в любом POSIX-шелле.
 */
export function quoteArg(arg: string): string {
  if (SAFE.test(arg)) return arg;
  return `'${arg.replaceAll("'", `'"'"'`)}'`;
}

/**
 * Единственный элемент уходит как есть — пайпы, редиректы и `VAR=x cmd`
 * исполняет удалённый шелл; несколько элементов квотируются поэлементно.
 * Тип требует хотя бы одного элемента: пустая команда — отказ вызывающего
 * (`specs/ssh.md`), а не `sh -c ''` с кодом 0.
 */
export function shellCommand(command: readonly [string, ...string[]]): string {
  if (command.length === 1) return command[0];
  return command.map(quoteArg).join(" ");
}
