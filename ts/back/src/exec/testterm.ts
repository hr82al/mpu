/**
 * Процесс, которого `SIGTERM` не снимает, — для теста «не ушёл по
 * SIGTERM — снимается по сроку» (`ssh.test.ts`): свой обработчик
 * отменяет умолчание, строка «готов» — когда он стоит. Модуль запускают
 * только тесты.
 */

import process from "node:process";

process.on("SIGTERM", () => {});
// Таймер держит процесс живым: у Node обработчик сигнала и вечный
// промис цикл событий не держат, и процесс вышел бы сам.
setInterval(() => {}, 60_000);
console.log("готов");
